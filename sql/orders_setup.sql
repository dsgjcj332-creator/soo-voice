-- This is the ONE script the dine-in QR flow needs. It covers every
-- guest-side failure mode we have seen:
--
--   1. Table missing        → guest sees "تعذّر الإرسال — حاول مرة أخرى"
--      (PostgREST code PGRST205 / "Could not find the table 'orders'").
--      → fixed by the create table below.
--
--   2. RLS blocks anon INSERT → guest sees
--      "الطلب مرفوض — يحتاج المطعم لتفعيل صلاحية الإدخال".
--      → fixed by the orders_public_insert policy.
--
--   3. Guest tracking stuck on "بانتظار المطبخ" forever because anon
--      cannot SELECT the status row.
--      → fixed by the orders_public_read policy.
--
--   4. Kitchen dashboard never refreshes → anon UPDATE blocked on some
--      edge flows. → fixed by the orders_public_update_status policy.
--
-- Safe to re-run: every statement is idempotent (IF NOT EXISTS /
-- DROP POLICY IF EXISTS first). It does NOT touch existing rows.

-- ============================================================
-- 1. Table (only created if it does not already exist)
-- ============================================================
create table if not exists orders (
  id            text primary key,           -- 'order_123456' generated by the guest app
  "ownerId"     text not null,              -- merchant uid the order belongs to
  "tableNumber" text,                       -- normalized to western digits by the app
  items         jsonb default '[]'::jsonb,  -- [{id, name, price, quantity}]
  total         numeric default 0,
  status        text default 'pending',     -- pending | preparing | completed | cancelled
  "createdAt"   bigint default 0            -- epoch millis
);

-- Kitchen queries are always "this merchant's orders, newest first".
create index if not exists orders_owner_created_idx
  on orders ("ownerId", "createdAt" desc);

-- ============================================================
-- 2. Row Level Security — authenticated merchant owner only
-- ============================================================
-- Anonymous guest checkout/tracking is intentionally disabled here.
-- Do not add public SELECT/UPDATE policies. A secure guest capability-token
-- endpoint must be implemented before anonymous tracking can be re-enabled.
alter table orders enable row level security;

drop policy if exists "orders_public_read" on orders;
drop policy if exists "orders_public_insert" on orders;
drop policy if exists "orders_public_update_status" on orders;
drop policy if exists "orders_authenticated_delete" on orders;

drop policy if exists "orders_owner_select" on orders;
drop policy if exists "orders_owner_insert" on orders;
drop policy if exists "orders_owner_update" on orders;
drop policy if exists "orders_owner_delete" on orders;

create policy "orders_owner_select"
  on orders for select
  to authenticated
  using ("ownerId" = auth.uid()::text);

create policy "orders_owner_insert"
  on orders for insert
  to authenticated
  with check ("ownerId" = auth.uid()::text);

create policy "orders_owner_update"
  on orders for update
  to authenticated
  using ("ownerId" = auth.uid()::text)
  with check ("ownerId" = auth.uid()::text);

create policy "orders_owner_delete"
  on orders for delete
  to authenticated
  using ("ownerId" = auth.uid()::text);
